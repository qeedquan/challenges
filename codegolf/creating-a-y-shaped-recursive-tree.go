package main

import "fmt"

func main() {
	for i := 1; i <= 5; i++ {
		fmt.Printf("n=%d\n", i)
		tree(i)
	}
}

func tree(n int) {
	w := 100
	h := 63
	p := alloc(w, h)
	recurse(p, n, w/2-1, h-1, 16)
	draw(p)
}

func alloc(w, h int) [][]byte {
	p := make([][]byte, h)
	for y := range p {
		p[y] = make([]byte, w)
		for x := range p[y] {
			p[y][x] = '_'
		}
	}
	return p
}

func recurse(p [][]byte, n, x, y, s int) {
	if n < 1 || n > 5 {
		return
	}
	for i := range s {
		p[y-i][x] = '1'
		p[y-s-i][x-i-1] = '1'
		p[y-s-i][x+i+1] = '1'
	}
	recurse(p, n-1, x-s, y-(2*s), s/2)
	recurse(p, n-1, x+s, y-(2*s), s/2)
}

func draw(p [][]byte) {
	for y := range p {
		fmt.Printf("%s\n", p[y])
	}
	fmt.Println()
}
