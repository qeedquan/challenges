import numpy as np

"""

Ported from @m90 solution

Takes ceil(n/2)

How it works
Broadcasting is used in several places to produce the table.

The bottom-left section
Change coordinates to a=−x+y and b=−x−y, as shown here (a blue, b yellow):

https://i.sstatic.net/3m1zG.png

This part is handled by the subexpression (4<<(a:=(y:=c_[1-n:n])-y.T)//4)+a%4-2&a-2*y. (y.T produces x.)

Looking at the lines of constant nonnegative even a, their squares are black when certain bits of  b are zero,
specifically (1x, 10x, 11x, 100x, 111x, 1000x, 1111x, ...) -- the low bit does not matter as it is always 0 in  b here.
These values are produced by taking a power of 2 and adding 0 or -2; then bitwise-ANDing with b
yields 0 for black squares and nonzero values for white squares.

The lines of constant nonnegative odd a are all white.
To get this to work, since the low bit of  b is 1 here, we just need to make sure the low bit of the value ANDed with  b is 1.

The top-right section
Here, a square is black iff y is odd, thus black iff y%2 is 1.

Combining the sections
Doubling the first part and subtracting 1 from it makes it negative for black squares and
positive for white squares in the bottom-left section.
In numpy arrays, shifting by a negative number produces zero,
so <<a makes it zero in the top-right section while preserving its sign in the bottom-left section.
Finally, it is less than y%2 iff it is negative (for a black square in the bottom-left section)
or it is 0 and y%2 is 1 (for a black square in the top-right section).

"""
def pattern(n):
    n = n//2 + n%2
    Y = np.c_[1 - n : n]
    A = Y - Y.T
    S = 4 << (A // 4)
    V = (S + A%4 - 2) & (A-2 * Y)
    return ((2*V - 1) << A) < (Y%2)

def draw(A):
    print("n=%d" % len(A))
    for i in range(len(A)):
        for j in range(len(A[i])):
            if A[i][j]:
                print('X', end='')
            else:
                print('.', end='')
        print()
    print()

def main():
    draw(pattern(1))
    draw(pattern(3))
    draw(pattern(7))
    draw(pattern(15))
    draw(pattern(25))

main()
