int
match(const char *str)
{
	static const PCRE2_SPTR pat = (PCRE2_SPTR) "^(?!.*(?=(.))((.{9})+|(.(?!(?3)*$))+|(?(?=.(...)*$)(.(?!(.{27})*$)){7}|.)+)\\1)";

	pcre2_code *re;
	pcre2_match_data *matchdata;
	size_t erroff;
	int errnum;
	int ret;

	re = pcre2_compile(pat, PCRE2_ZERO_TERMINATED, 0, &errnum, &erroff, NULL);
	if (!re)
		return -EINVAL;

	matchdata = pcre2_match_data_create_from_pattern(re, NULL);
	if (!matchdata)
		goto error;

	ret = pcre2_match(re, (PCRE2_SPTR)str, PCRE2_ZERO_TERMINATED, 0, 0, matchdata, NULL);
	if (ret < 0)
		ret = 0;

	if (0) {
	error:
		ret = -errno;
	}

	pcre2_match_data_free(matchdata);
	pcre2_code_free(re);
	return ret;
}

