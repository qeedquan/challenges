#include <stdio.h>

void
solve(int c)
{
	int a, b;
	int x, y;

	printf("%d: ", c);
	for (a = 1; a < c; a++) {
		for (b = a; b < c; b++) {
			x = (a * a) + a + (b * b) + b;
			y = (c * c) + c;
			if (x == y)
				printf("(%d, %d) ", a, b);
		}
	}
	printf("\n");
}

